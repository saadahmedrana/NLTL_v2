# General file utilities
# -----------------------------------------------------------------------------
def read_text(path: Path | None) -> str:
    if path is None:
        return "[NO PATH PROVIDED]"
    if not path.exists():
        return f"[MISSING FILE: {path}]"
    try:
        text = path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        text = path.read_text(encoding="latin-1")
    text = text.strip()
    return text if text else f"[EMPTY FILE: {path}]"


def read_json(path: Path | None) -> Any:
    if path is None or not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None


def read_json_pretty(path: Path | None) -> str:
    data = read_json(path)
    if data is not None:
        return json.dumps(data, indent=2, ensure_ascii=False)
    return read_text(path)


def first_existing(paths: Iterable[Path]) -> Path | None:
    for path in paths:
        if path.exists():
            return path
    return None


def resolve_maybe_relative_path(raw: str, project_root: Path) -> Path | None:
    raw = str(raw or "").strip().strip('"').strip("'")
    if not raw:
        return None
    path = Path(raw).expanduser()
    if path.is_absolute():
        return path
    return project_root / path


def resolve_pointer_file(pointer_file: Path, project_root: Path) -> Path | None:
    """Resolve files such as ship_file.txt or input_file.txt that contain a path."""
    if not pointer_file.exists():
        return None
    raw = read_text(pointer_file)
    if raw.startswith("["):
        return None
    return resolve_maybe_relative_path(raw, project_root)


def case_id_from_run_dir(run_dir: Path) -> str:
    return run_dir.name.split("__", 1)[0]


def case_number_from_case_id(case_id: str) -> int | None:
    match = re.match(r"^(\d+)_", case_id)
    if not match:
        return None
    return int(match.group(1))


def case_number_string(case_id: str) -> str:
    n = case_number_from_case_id(case_id)
    return f"{n:02d}" if n is not None else case_id


def case_sort_key(path: Path) -> tuple[int, str]:
    case_id = case_id_from_run_dir(path)
    n = case_number_from_case_id(case_id)
    if n is None:
        return 10**9, case_id
    return n, case_id


def chunk_list(items: list[Path], chunk_size: int) -> list[list[Path]]:
    return [items[i : i + chunk_size] for i in range(0, len(items), chunk_size)]


def file_has_real_shacl(path: Path) -> bool:
    if not path.exists() or path.stat().st_size == 0:
        return False
    text = read_text(path)
    markers = [
        "sh:NodeShape",
        "sh:PropertyShape",
        "sh:sparql",
        "sh:property",
        "@prefix sh:",
        "PREFIX sh:",
    ]
    return any(marker in text for marker in markers)


# -----------------------------------------------------------------------------
# Optional CSV metadata support
# -----------------------------------------------------------------------------
def read_csv_rows(csv_path: Path) -> dict[str, dict[str, str]]:
    """Read results.csv if it exists. The script still works without it."""
    if not csv_path.exists():
        return {}

    with csv_path.open("r", encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))

    out: dict[str, dict[str, str]] = {}
    for row in rows:
        case_id = row.get("case_id", "").strip()
        run_folder = row.get("run_folder", "").strip()
        if case_id:
            out[case_id] = row
        if run_folder:
            folder_case = Path(run_folder).name.split("__", 1)[0]
            if folder_case:
                out[folder_case] = row
    return out


# -----------------------------------------------------------------------------
# Few-shot extraction and de-duplication
# -----------------------------------------------------------------------------
def normalise_fewshot_json(data: Any) -> list[dict[str, Any]]:
    """Return a list of few-shot example dicts from several possible JSON shapes."""
    if data is None:
        return []

    if isinstance(data, list):
        return [x for x in data if isinstance(x, dict)]

    if isinstance(data, dict):
        for key in (
            "fewshot_examples",
            "few_shot_examples",
            "fewshots",
            "few_shots",
            "examples",
            "selected_examples",
            "items",
        ):
            value = data.get(key)
            if isinstance(value, list):
                return [x for x in value if isinstance(x, dict)]

        # Sometimes the file itself is one example dict.
        if any(k in data for k in ("id", "title", "regulation_text", "shacl_output")):
            return [data]

    return []


def example_key(example: dict[str, Any]) -> str:
    """Stable de-dup key for few-shot examples."""
    for key in ("id", "case_id", "title"):
        value = str(example.get(key, "")).strip()
        if value:
            return f"{key}:{value}"
    fallback = json.dumps(example, sort_keys=True, ensure_ascii=False)
    return fallback[:500]


def read_fewshot_examples(path: Path | None) -> list[dict[str, Any]]:
    data = read_json(path)
    examples = normalise_fewshot_json(data)

    seen: set[str] = set()
    out: list[dict[str, Any]] = []
    for ex in examples:
        key = example_key(ex)
        if key in seen:
            continue
        seen.add(key)
        out.append(ex)
    return out


def groups_in_chunk(chunk: list[Path]) -> list[str]:
    ordered: list[str] = []
    for run_dir in chunk:
        case_id = case_id_from_run_dir(run_dir)
        n = case_number_from_case_id(case_id)
        group = group_from_case_number(n) if n is not None else "other"
        if group not in ordered:
            ordered.append(group)
    return ordered


def find_fewshot_source_for_group(
    group: str,
    chunk: list[Path],
    all_run_folders: list[Path],
) -> Path | None:
    """Find one fewshot_used.json file for this group. Prefer current batch, then whole run."""
    def same_group(run_dir: Path) -> bool:
        case_id = case_id_from_run_dir(run_dir)
        n = case_number_from_case_id(case_id)
        return group_from_case_number(n) == group if n is not None else group == "other"

    for run_dir in chunk:
        p = run_dir / "fewshot_used.json"
        if same_group(run_dir) and p.exists():
            return p

    for run_dir in all_run_folders:
        p = run_dir / "fewshot_used.json"
        if same_group(run_dir) and p.exists():
            return p

    return None


def build_fewshot_section(chunk: list[Path], all_run_folders: list[Path]) -> str:
    sections: list[str] = []

    for group in groups_in_chunk(chunk):
        source = find_fewshot_source_for_group(group, chunk, all_run_folders)
        examples = read_fewshot_examples(source)

        if examples:
            examples_text = json.dumps(examples, indent=2, ensure_ascii=False)
        else:
            examples_text = "[NO FEW-SHOT EXAMPLES FOUND FOR THIS GROUP]"

        source_text = str(source) if source else "[NO SOURCE FILE FOUND]"
        sections.append(
            f"""--------------------------------------------------------------------------------
FEW-SHOT EXAMPLES FOR {group_label(group)}
Source fewshot_used.json: {source_text}
These examples apply to all test cases in this batch with this group. Do not score these examples.
--------------------------------------------------------------------------------
{examples_text}"""
        )

    return "\n\n".join(sections)


