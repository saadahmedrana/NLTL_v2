def group_from_case_number(case_number: int) -> str:
    """Map thesis case number to the broad regulation type."""
    if 1 <= case_number <= 24:
        return "static"
    if 25 <= case_number <= 40:
        return "static_calculation"
    if 41 <= case_number <= 82:
        return "complex_readiness"
    if 83 <= case_number <= 90:
        return "dynamic"
    return "other"


def group_label(group: str) -> str:
    return {
        "static": "Static cases 01-24",
        "static_calculation": "Static-calculation cases 25-40",
        "complex_readiness": "Complex/readiness cases 41-82",
        "dynamic": "Dynamic/simulation-readiness cases 83-90",
        "other": "Other / unclassified cases",
    }.get(group, group)


