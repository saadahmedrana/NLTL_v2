def make_batches_for_experiment(
    experiment_dir: Path,
    output_root: Path,
    project_root: Path,
    batch_size: int,
    ship_mode: str,
) -> dict[str, Any]:
    experiment_dir = experiment_dir.expanduser()
    runs_dir = experiment_dir / "runs"
    results_csv = experiment_dir / "results.csv"
    output_dir = output_root / experiment_dir.name

    if not runs_dir.exists():
        raise FileNotFoundError(f"Runs directory does not exist: {runs_dir}")

    run_folders = sorted([p for p in runs_dir.iterdir() if p.is_dir()], key=case_sort_key)
    if not run_folders:
        raise ValueError(f"No run folders found in: {runs_dir}")

    rows_by_case = read_csv_rows(results_csv)
    output_dir.mkdir(parents=True, exist_ok=True)

    chunks = chunk_list(run_folders, batch_size)
    manifest_rows: list[dict[str, Any]] = []

    for batch_index, chunk in enumerate(chunks, start=1):
        start_case = case_id_from_run_dir(chunk[0])
        end_case = case_id_from_run_dir(chunk[-1])
        batch_name = f"{experiment_dir.name}__batch_{batch_index:02d}__{start_case}_TO_{end_case}.txt"
        batch_path = output_dir / batch_name

        ship_ttl_section = build_ship_ttl_section(chunk, project_root, ship_mode)
        fewshot_section = build_fewshot_section(chunk, run_folders)

        case_blocks: list[str] = []
        for local_index, run_dir in enumerate(chunk, start=1):
            case_id = case_id_from_run_dir(run_dir)
            row = rows_by_case.get(case_id, {})
            case_blocks.append(build_case_block(run_dir, row, local_index, project_root))

        case_numbers = [case_number_string(case_id_from_run_dir(p)) for p in chunk]

        content = f"""COMBINED BINARY SHACL/TURTLE EVALUATION BATCH
Generated: {datetime.now().isoformat(timespec="seconds")}
Experiment: {experiment_dir.name}
Batch: {batch_index}/{len(chunks)}
Cases in this file: {len(chunk)}
Range: {start_case} to {end_case}
Case numbers expected in output: {", ".join(case_numbers)}

{BINARY_EVALUATION_INSTRUCTIONS}

================================================================================
INPUT TTL CONTEXT
================================================================================
{ship_ttl_section}

================================================================================
FEW-SHOT CONTEXT, DEDUPLICATED BY REQUIREMENT GROUP
================================================================================
{fewshot_section}

================================================================================
TEST CASES TO SCORE
================================================================================
{chr(10).join(case_blocks)}
"""

        batch_path.write_text(content, encoding="utf-8")
        print(f"[WROTE] {batch_path}")

        manifest_rows.append(
            {
                "experiment": experiment_dir.name,
                "batch_file": str(batch_path),
                "batch_index": batch_index,
                "start_case": start_case,
                "end_case": end_case,
                "case_count": len(chunk),
                "case_numbers": "|".join(case_numbers),
                "case_ids": "|".join(case_id_from_run_dir(p) for p in chunk),
            }
        )

    manifest_path = output_dir / f"{experiment_dir.name}__manifest.csv"
    with manifest_path.open("w", encoding="utf-8", newline="") as f:
        fieldnames = [
            "experiment",
            "batch_file",
            "batch_index",
            "start_case",
            "end_case",
            "case_count",
            "case_numbers",
            "case_ids",
        ]
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(manifest_rows)

    print(f"[WROTE] {manifest_path}")

    return {
        "experiment": experiment_dir.name,
        "run_folder_count": len(run_folders),
        "batch_count": len(chunks),
        "output_dir": str(output_dir),
        "manifest": str(manifest_path),
    }


def parse_experiment_dirs(values: list[str] | None) -> list[Path]:
    if not values:
        return DEFAULT_EXPERIMENT_DIRS
    out: list[Path] = []
    for value in values:
        # Allow comma-separated or repeated --experiment-dir values.
        for part in value.split(","):
            part = part.strip()
            if part:
                out.append(Path(part).expanduser())
    return out


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Create LLM-evaluation batch txt files for run2 and run3. "
            "Each batch includes input TTL context, de-duplicated few-shot examples per regulation type, "
            "input regulation JSON, and final_generated_shacl.ttl."
        )
    )
    parser.add_argument("--project-root", type=Path, default=PROJECT_ROOT)
    parser.add_argument(
        "--experiment-dir",
        action="append",
        default=None,
        help=(
            "Experiment folder(s). Can be repeated or comma-separated. "
            "Default: no-context TRUE run2 and TRUE run3 experiments."
        ),
    )
    parser.add_argument("--output-root", type=Path, default=DEFAULT_OUTPUT_ROOT)
    parser.add_argument("--batch-size", type=int, default=10)
    parser.add_argument(
        "--ship-mode",
        choices=["once", "per-case", "none"],
        default="once",
        help=(
            "How to include the input TTL/ship graph. 'once' includes one graph per batch; "
            "'per-case' repeats it for each case; 'none' leaves it out. Default: once."
        ),
    )

    args = parser.parse_args()

    project_root = args.project_root.expanduser()
    output_root = args.output_root.expanduser()
    experiment_dirs = parse_experiment_dirs(args.experiment_dir)
    batch_size = args.batch_size
    ship_mode = args.ship_mode

    if batch_size < 1:
        raise ValueError("--batch-size must be >= 1")

    output_root.mkdir(parents=True, exist_ok=True)

    all_summaries: list[dict[str, Any]] = []
    for experiment_dir in experiment_dirs:
        print()
        print(f"[EXPERIMENT] {experiment_dir}")
        summary = make_batches_for_experiment(
            experiment_dir=experiment_dir,
            output_root=output_root,
            project_root=project_root,
            batch_size=batch_size,
            ship_mode=ship_mode,
        )
        all_summaries.append(summary)

    combined_manifest = output_root / "combined_run2_run3_manifest.csv"
    with combined_manifest.open("w", encoding="utf-8", newline="") as f:
        fieldnames = ["experiment", "run_folder_count", "batch_count", "output_dir", "manifest"]
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(all_summaries)

    print()
    print("[DONE]")
    print(f"Batch size: {batch_size}")
    print(f"Ship mode: {ship_mode}")
    print(f"Output root: {output_root}")
    print(f"Combined manifest: {combined_manifest}")


if __name__ == "__main__":
    main()
