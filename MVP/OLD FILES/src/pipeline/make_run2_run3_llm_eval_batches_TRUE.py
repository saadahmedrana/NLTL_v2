def find_input_regulation(run_dir: Path, row: dict[str, str], project_root: Path) -> str:
    """Find the actual regulation JSON for a run."""
    direct = run_dir / "input_regulation.json"
    if direct.exists():
        return read_json_pretty(direct)

    pointer = resolve_pointer_file(run_dir / "input_file.txt", project_root)
    if pointer and pointer.exists():
        return read_json_pretty(pointer)

    # Optional fallbacks from results.csv if present.
    rel = row.get("input_relative_path", "").strip()
    if rel:
        candidates = [
            project_root / rel,
            project_root / "data/input/input_all" / rel,
            project_root / "data/input" / rel,
        ]
        p = first_existing(candidates)
        if p:
            return read_json_pretty(p)

    filename = row.get("input_filename", "").strip()
    if filename:
        for root in [project_root / "data/input/input_all", project_root / "data/input"]:
            if root.exists():
                matches = list(root.rglob(filename))
                if matches:
                    return read_json_pretty(matches[0])

    return "[INPUT REGULATION JSON NOT FOUND]"


def resolve_ship_ttl_path(run_dir: Path, project_root: Path) -> Path | None:
    """Find the TTL/ship graph for a run."""
    # Most useful/likely: a pointer file in the run folder.
    pointer = resolve_pointer_file(run_dir / "ship_file.txt", project_root)
    if pointer and pointer.exists():
        return pointer

    # Direct files sometimes copied into run folders.
    direct_candidates = [
        run_dir / "input.ttl",
        run_dir / "ship.ttl",
        run_dir / "master_ship_1.ttl",
        run_dir / "input_ship.ttl",
        run_dir / "data_graph.ttl",
    ]
    p = first_existing(direct_candidates)
    if p:
        return p

    # Common project-level fallbacks. Add/change these if your local file name differs.
    fallback_names = ["master_ship_1.ttl", "ship.ttl", "ship.txt"]
    search_roots = [project_root, project_root / "data", project_root / "data/input"]
    for root in search_roots:
        if not root.exists():
            continue
        for name in fallback_names:
            matches = list(root.rglob(name))
            if matches:
                return matches[0]

    return None


def build_ship_ttl_section(
    chunk: list[Path],
    project_root: Path,
    ship_mode: str,
) -> str:
    """Build input TTL context section. Modes: once, per-case, none."""
    if ship_mode == "none":
        return "INPUT TTL / SHIP GRAPH CONTEXT: [NOT INCLUDED BY SCRIPT OPTION]"

    if ship_mode == "once":
        # Use first resolvable ship graph in the batch. In this thesis setup it should be the same master ship graph.
        source: Path | None = None
        for run_dir in chunk:
            source = resolve_ship_ttl_path(run_dir, project_root)
            if source:
                break
        if not source:
            return "INPUT TTL / SHIP GRAPH CONTEXT: [SHIP TTL FILE NOT FOUND]"

        return f"""INPUT TTL / SHIP GRAPH CONTEXT FOR ALL TEST CASES IN THIS BATCH
Source: {source}

{read_text(source)}"""

    if ship_mode == "per-case":
        parts: list[str] = []
        for run_dir in chunk:
            case_id = case_id_from_run_dir(run_dir)
            source = resolve_ship_ttl_path(run_dir, project_root)
            if source:
                ttl = read_text(source)
                source_text = str(source)
            else:
                ttl = "[SHIP TTL FILE NOT FOUND]"
                source_text = "[NOT FOUND]"
            parts.append(
                f"""INPUT TTL / SHIP GRAPH FOR {case_id}
Source: {source_text}

{ttl}"""
            )
        return "\n\n".join(parts)

    raise ValueError(f"Unknown ship_mode: {ship_mode}")


