def compact_summary(run_dir: Path, row: dict[str, str]) -> str:
    summary_path = run_dir / "final_summary.json"
    summary = read_json(summary_path) or {}
    case_id = case_id_from_run_dir(run_dir)
    n = case_number_from_case_id(case_id)

    compact = {
        "case_number": case_number_string(case_id),
        "case_id": summary.get("case_id") or row.get("case_id") or case_id,
        "shape_name": summary.get("shape_name") or row.get("shape_name"),
        "category": summary.get("category") or row.get("category"),
        "requirement_type": summary.get("requirement_type") or row.get("requirement_type"),
        "script_group": group_from_case_number(n) if n is not None else "other",
        "title": summary.get("title") or row.get("title"),
        "model_name": summary.get("model_name") or row.get("model_name"),
        "ablation": summary.get("ablation") or row.get("ablation") or "no_validator_generator_only",
        "validator_enabled": summary.get("validator_enabled", False),
        "syntax_checker_enabled": summary.get("syntax_checker_enabled", False),
        "ship_validation_enabled": summary.get("ship_validation_enabled", False),
        "shacl_extraction_ok": summary.get("shacl_extraction_ok"),
        "shacl_extraction_error": summary.get("shacl_extraction_error", ""),
        "final_shacl_hash": summary.get("final_shacl_hash") or row.get("final_shacl_hash"),
    }

    # Remove empty None values but keep False values.
    compact = {k: v for k, v in compact.items() if v is not None and v != ""}
    return json.dumps(compact, indent=2, ensure_ascii=False)


def build_case_block(
    run_dir: Path,
    row: dict[str, str],
    local_index: int,
    project_root: Path,
) -> str:
    case_id = case_id_from_run_dir(run_dir)
    case_number = case_number_string(case_id)
    n = case_number_from_case_id(case_id)
    group = group_from_case_number(n) if n is not None else "other"

    final_shacl_path = run_dir / "final_generated_shacl.ttl"
    if file_has_real_shacl(final_shacl_path):
        final_shacl = read_text(final_shacl_path)
    else:
        final_shacl = "[NO FINAL SHACL/TURTLE CODE WAS PRODUCED OR FILE IS EMPTY]"

    input_regulation = find_input_regulation(run_dir, row, project_root)
    summary = compact_summary(run_dir, row)

    return f"""================================================================================
TEST CASE {local_index}
CASE_NUMBER: {case_number}
CASE_ID: {case_id}
REQUIREMENT_GROUP: {group_label(group)}
================================================================================

COMPACT CASE SUMMARY
{summary}

--------------------------------------------------------------------------------
ORIGINAL INPUT REGULATION JSON / TEXT
--------------------------------------------------------------------------------
{input_regulation}

--------------------------------------------------------------------------------
GENERATED FINAL SHACL / TURTLE CODE FOR THIS RUN
--------------------------------------------------------------------------------
{final_shacl}
"""


